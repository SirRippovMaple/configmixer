package mixin

import (
	"encoding/json"
	"fmt"
	"strings"
)

// SelectionCommentPrefix marks the line in a generated .env file that embeds
// the mixin selection used to produce it. dotenv.Parse already ignores
// '#'-prefixed lines, so this line is invisible to normal .env consumers.
const SelectionCommentPrefix = "# configmixer-selection: "

// EncodeSelectionComment renders sel as a single marker comment line mapping
// category to the chosen mixin ID.
func EncodeSelectionComment(sel Selection) (string, error) {
	ids := make(map[string]string, len(sel))
	for category, m := range sel {
		ids[category] = m.ID
	}
	data, err := json.Marshal(ids)
	if err != nil {
		return "", fmt.Errorf("encoding mixin selection: %w", err)
	}
	return SelectionCommentPrefix + string(data), nil
}

// DecodeSelectionComment scans lines for the marker comment written by
// EncodeSelectionComment and returns the embedded category -> mixin ID
// mapping. It returns an error if no marker line is found.
func DecodeSelectionComment(lines []string) (map[string]string, error) {
	for _, line := range lines {
		rest, ok := strings.CutPrefix(line, SelectionCommentPrefix)
		if !ok {
			continue
		}
		var ids map[string]string
		if err := json.Unmarshal([]byte(rest), &ids); err != nil {
			return nil, fmt.Errorf("parsing embedded mixin selection: %w", err)
		}
		return ids, nil
	}
	return nil, fmt.Errorf("no embedded mixin selection found; this file wasn't generated by configmixer, or predates the regenerate feature")
}
